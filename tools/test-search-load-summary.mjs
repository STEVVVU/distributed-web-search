import assert from 'node:assert/strict';
import {assertRankedResults, loadSummary, quantiles} from './search-load-summary.mjs';
const saturation = loadSummary([{correct: true}, {rejected: 'generator ceiling'}, {error: 'timeout', timeout: true}, {rejected: 'HTTP 503', error: 'HTTP 503'}]);
assert.deepEqual(saturation.counts, {offered: 4, completed: 1, rejected: 2, failed: 1, timedOut: 1, integrityErrors: 0});
assert(saturation.measurementComplete && saturation.correctOutputs && !saturation.zeroLossEnvelope);
assert.equal(loadSummary([{error: 'wrong result order', integrityError: true}]).correctOutputs, false);
assert.equal(loadSummary([{correct: true}]).zeroLossEnvelope, true);
assert.throws(() => loadSummary([{}]), /terminal outcome/);
assert.throws(() => loadSummary([{correct: true, error: 'invalid'}]), /terminal outcome/);
const expected = [{url: 'http://127.0.0.1/doc', title: 'Doc', text: 'Text', score: 3, lexical: 2, rank: 1}];
assert.doesNotThrow(() => assertRankedResults(expected, expected));
for (const key of ['url', 'title', 'text', 'score', 'lexical', 'rank']) assert.throws(() => assertRankedResults([{...expected[0], [key]: typeof expected[0][key] === 'string' ? 'wrong' : NaN}], expected), /oracle/);
assert.equal(quantiles([]).p50, null);
assert.equal(quantiles([1, 2, 3]).p99, null);
assert.equal(quantiles(Array.from({length: 100}, (_, i) => i)).p99, 98);
console.log('Search load accounting separates completed measurements, output integrity and zero-loss envelope');
